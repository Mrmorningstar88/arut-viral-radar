export function demoBoard(): FormatBoard {
  const reels: FormatReel[] = SEED.map(([format, views, hook], i) => ({
    id: `demo-${i}`,
    author: ["moneyfacts", "macro_daily", "fin.truth", "trader.notes"][i % 4],
    views,
    likes: Math.round(views * (0.03 + ((i * 7) % 9) / 300)),
    coverUrl: null,
    hook,
    format,
    confidence: 0.8,
  }));
  return { shared: false, reels, unlabeled: 0, ...rankFormats(reels.map((r) => ({ format: r.format!, views: r.views }))) };
}
